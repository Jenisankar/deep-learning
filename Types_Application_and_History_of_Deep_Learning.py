# ==============================================================
# 🧩 Categories of Neural Networks
# ==============================================================

# 1️⃣ MLP — Multi-Layer Perceptron
# --------------------------------
# - A fundamental neural network architecture, also known as a feedforward network.
# - Neurons in one layer are fully connected to neurons in the next layer.
# - Commonly applied to structured or tabular datasets and basic classification tasks.

# 2️⃣ ANN — Artificial Neural Network
# -----------------------------------
# - A broad term that refers to neural networks in general.
# - Typically organized into input, hidden, and output layers.
# - Learning occurs by updating connection weights during training.

# 3️⃣ CNN — Convolutional Neural Network
# --------------------------------------
# - Designed specifically for processing visual data such as images and videos.
# - Uses convolution operations to capture local patterns like edges and textures.
# - Widely used in:
#     - Facial recognition systems
#     - Object localization and detection
#     - Medical image diagnostics

# 4️⃣ RNN — Recurrent Neural Network
# ----------------------------------
# - Built to handle sequential or time-dependent data.
# - Maintains internal memory to capture information from previous steps.
# - Popular variants include:
#     - LSTM (Long Short-Term Memory)
#     - GRU (Gated Recurrent Unit)
# - Common use cases:
#     - Language modeling
#     - Sequence generation
#     - Financial time-series analysis

# 5️⃣ Autoencoder
# ----------------
# - An unsupervised neural network that learns compact data representations.
# - Encodes input into a lower-dimensional space and then reconstructs it.
# - Used for:
#     - Feature extraction
#     - Noise removal
#     - Data compression

# 6️⃣ GAN — Generative Adversarial Network
# ----------------------------------------
# - Composed of two competing models:
#     - Generator: produces synthetic samples
#     - Discriminator: evaluates real vs generated data
# - Both networks improve through adversarial training.
# - Applications include:
#     - Image synthesis
#     - Style and image translation
#     - Deepfake generation
#     - Creative AI and digital art


